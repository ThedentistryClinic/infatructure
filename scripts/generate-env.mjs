#!/usr/bin/env node
// Generate web/js/env.js from .env.<mode> (development | production | staging).
//   node scripts/generate-env.mjs development
// Only PUBLIC values are written. The script refuses service-role / secret keys.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mode = process.argv[2] || process.env.APP_ENV || 'development';
const file = resolve(root, `.env.${mode}`);
if (!existsSync(file)) {
  console.error(`Missing ${file}. Copy .env.${mode}.example and fill it in.`);
  process.exit(1);
}
const env = {};
for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
  const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/.exec(line);
  if (m && !line.trim().startsWith('#')) env[m[1]] = m[2].replace(/^['"]|['"]$/g, '');
}
// Allow CI to override with real environment variables
for (const k of ['SUPABASE_URL', 'SUPABASE_ANON_KEY', 'APP_BASE_URL']) if (process.env[k]) env[k] = process.env[k];

const fail = (msg) => { console.error(`✖ ${msg}`); process.exit(1); };
if (!/^https:\/\/|^http:\/\/(localhost|127\.0\.0\.1)/.test(env.SUPABASE_URL || '')) fail('SUPABASE_URL is missing or not https');
if (!env.SUPABASE_ANON_KEY) fail('SUPABASE_ANON_KEY is missing');
const key = env.SUPABASE_ANON_KEY;
let role = null;
try { role = JSON.parse(Buffer.from(key.split('.')[1], 'base64url').toString()).role; } catch { /* publishable key format */ }
if (key.startsWith('sb_secret_') || role === 'service_role') fail('Refusing to ship a service_role / secret key to the browser');
if (mode === 'production' && /localhost|127\.0\.0\.1/.test(env.SUPABASE_URL)) fail('Production config points to localhost');

const config = {
  APP_ENV: mode,
  SUPABASE_URL: env.SUPABASE_URL,
  SUPABASE_ANON_KEY: key,
  APP_BASE_URL: env.APP_BASE_URL || '',
  ADMIN_USERS_FUNCTION: env.ADMIN_USERS_FUNCTION || 'admin-users',
};
const out = resolve(root, 'web/js/env.js');
writeFileSync(out, `// Generated by scripts/generate-env.mjs (${mode}) — do not edit or commit.\nwindow.APP_CONFIG = ${JSON.stringify(config, null, 2)};\n`);
console.log(`✔ wrote ${out} for "${mode}"`);
